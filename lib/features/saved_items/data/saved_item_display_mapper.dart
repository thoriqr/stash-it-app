/// The three enrichment status values used by the API.
const String _pending = 'pending';
const String _completed = 'completed';
const String _failed = 'failed';

/// Maps an API enrichment status to its presentation value.
///
/// Shared by saved item listings and Search so the same status is interpreted
/// consistently across features.
///
/// Unknown values fall back to [EnrichmentStatus.pending]. This is a defensive
/// fallback because the API defines only three values. Pending makes no
/// assumption about whether enrichment succeeded or failed.
EnrichmentStatus enrichmentStatusFrom(String wire) => switch (wire) {
  _completed => EnrichmentStatus.completed,
  _failed => EnrichmentStatus.failed,
  _pending => EnrichmentStatus.pending,
  _ => EnrichmentStatus.pending,
};

/// Creates the typed saved-time value from the item's `created_at` value.
///
/// Shared by Inbox, Search, collection listings and detail so all features
/// interpret elapsed time consistently. The buckets are: less than one minute,
/// less than one hour, less than one day, "yesterday" between 24 and 48 hours,
/// and whole days thereafter.
///
/// The value is generated by the client; the API provides `created_at`, not a
/// preformatted time label. Presentation converts the result to localized copy.
///
/// `now` is injected to make the result deterministic in tests.
///
/// Returns null when `created_at` cannot be parsed or represents a future
/// timestamp. In either case, the client cannot reliably determine an elapsed
/// time and should not display a fabricated label.
SavedTime? savedTimeFrom(String createdAt, DateTime now) {
  final saved = DateTime.tryParse(createdAt);
  if (saved == null) return null;

  final elapsed = now.difference(saved.toLocal());

  // A future timestamp may indicate clock skew, so no elapsed-time label is shown.
  if (elapsed.isNegative) return null;

  if (elapsed.inMinutes < 1) return const SavedTime.justNow();
  if (elapsed.inHours < 1) return SavedTime.minutes(elapsed.inMinutes);
  if (elapsed.inHours < 24) return SavedTime.hours(elapsed.inHours);
  if (elapsed.inHours < 48) return const SavedTime.yesterday();

  return SavedTime.days(elapsed.inDays);
}
